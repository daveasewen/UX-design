"""Driven interactions, part 1: shared filters, persistence, theme, nav carry, drill-through, charts
(legend, tooltip, table), grid search/sort/page, keyboard open + Escape focus return."""
import os, json, re
from playwright.sync_api import sync_playwright
OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
U = lambda n: 'file://' + os.path.join(OUT, n)
R = []
def check(name, ok, detail=''):
    R.append(('PASS' if ok else 'FAIL', name, detail)); print(('PASS ' if ok else 'FAIL ') + name + ('  — ' + str(detail) if detail else ''))
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=os.environ['RENDER_SHELL'])
    ctx = b.new_context(viewport={'width': 1600, 'height': 1000}, accept_downloads=True)
    pg = ctx.new_page(); errs = []
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(U('index.html')); pg.evaluate('localStorage.clear()'); pg.reload(); pg.wait_for_timeout(600)
    cash0 = pg.text_content('[data-kpi="cash"] .amt')
    rows0 = pg.evaluate("document.querySelectorAll('#ch-exposure table.dv-table tbody tr').length")
    # entity filter through the Filter-toolbar dropdown
    pg.click('#dd-region-t'); check('region menu opens (data-open + aria-expanded)', pg.get_attribute('#dd-region-m', 'data-open') == 'true' and pg.get_attribute('#dd-region-t', 'aria-expanded') == 'true')
    pg.click('#dd-region-m [data-value="eu"]'); pg.wait_for_timeout(400)
    cash1 = pg.text_content('[data-kpi="cash"] .amt')
    check('region filter re-drives KPI', cash0 != cash1, cash0 + ' -> ' + cash1)
    check('region filter re-drives exposure chart', pg.evaluate("document.querySelectorAll('#ch-exposure table.dv-table tbody tr').length") == 1, 'rows now ' + str(pg.evaluate("document.querySelectorAll('#ch-exposure table.dv-table tbody tr').length")))
    check('filter reflected in URL', 'region=eu' in pg.url, pg.url.split('?')[-1])
    check('applied-filter chip shown', pg.locator('#ftb-chips .tag').count() == 1, pg.text_content('#ftb-chips'))
    check('entity menu narrowed to region', pg.evaluate("[...document.querySelectorAll('#dd-entity-m .opt')].length") == 3)
    pg.click('#dd-entity-t'); pg.click('#dd-entity-m [data-value="HLG"]'); pg.wait_for_timeout(400)
    cash2 = pg.text_content('[data-kpi="cash"] .amt')
    check('entity filter re-drives KPI', cash2 != cash1, cash1 + ' -> ' + cash2)
    pg.click('#dd-days-t'); pg.click('#dd-days-m [data-value="7"]'); pg.wait_for_timeout(400)
    check('date filter shortens the time series', pg.evaluate("document.querySelectorAll('#ch-liquidity table.dv-table tbody tr').length") == 7)
    # persistence across reload and page change
    pg.goto(U('index.html')); pg.wait_for_timeout(500)
    check('filters persist on a bare reload (localStorage)', pg.text_content('#dd-entity .ddval').startswith('Harbourline Logistics') and pg.text_content('[data-kpi="cash"] .amt') == cash2, pg.text_content('#dd-entity .ddval'))
    href = pg.get_attribute('.sn-link[href^="payments.html"]', 'href')
    check('nav links carry the shared filters', 'entity=HLG' in href and 'days=7' in href, href)
    pg.click('.sn-link[href^="accounts.html"]'); pg.wait_for_timeout(700)
    check('filters follow to a sub-page', 'Accounts' in pg.title() and pg.text_content('#dd-days .ddval') == 'Last 7 days' and all('Logistics' in t for t in pg.locator('#g-tx-body td:nth-child(4)').all_text_contents()), pg.text_content('#g-tx-count'))
    pg.click('[data-ftb-clear]'); pg.wait_for_timeout(400)
    check('clear all resets filters', pg.text_content('#g-tx-count') == '360 results' and 'entity' not in pg.url, pg.text_content('#g-tx-count'))
    # theme switch + persistence
    pg.click('[data-theme-btn="dark"]'); pg.wait_for_timeout(300)
    check('theme switch sets data-theme=dark on <html>', pg.get_attribute('html', 'data-theme') == 'dark' and pg.get_attribute('html', 'data-apollo-theme') == 'common')
    pg.goto(U('fx.html')); pg.wait_for_timeout(500)
    check('theme persists across pages', pg.get_attribute('html', 'data-theme') == 'dark' and pg.get_attribute('[data-theme-btn="dark"]', 'aria-pressed') == 'true')
    check('dark mode swaps the masthead mark', pg.evaluate("getComputedStyle(document.querySelector('.sh-mark[data-mode=dark]')).display") != 'none' and pg.evaluate("getComputedStyle(document.querySelector('.sh-mark[data-mode=light]')).display") == 'none')
    pg.click('[data-theme-btn="light"]')
    # grid search / sort / page / page size / keyboard open / Escape returns focus
    pg.goto(U('accounts.html')); pg.wait_for_timeout(500)
    pg.fill('[data-grid-search="g-tx"]', 'Rhein'); pg.wait_for_timeout(400)
    n = pg.text_content('#g-tx-count'); check('grid search filters rows', n != '360 results' and all('Rhein' in t for t in pg.locator('#g-tx-body td:nth-child(2)').all_text_contents()), n)
    pg.fill('[data-grid-search="g-tx"]', ''); pg.wait_for_timeout(400)
    pg.click('#g-tx button[data-sort="gbp"]'); pg.wait_for_timeout(200)
    v = pg.locator('#g-tx-body td:nth-child(7)').all_text_contents()
    num = [float(re.sub(r'[^0-9.\-]', '', x.replace('−', '-'))) for x in v]
    check('sort ascending by GBP', num == sorted(num) and pg.get_attribute('#g-tx th[data-key="gbp"]', 'aria-sort') == 'ascending', v[:3])
    pg.click('#g-tx button[data-sort="gbp"]'); pg.wait_for_timeout(200)
    check('second click sorts descending', pg.get_attribute('#g-tx th[data-key="gbp"]', 'aria-sort') == 'descending')
    pg.click('#g-tx-pg [data-grid-go="2"]'); pg.wait_for_timeout(200)
    check('paging moves to page 2', pg.text_content('#g-tx-range').startswith('26–50'), pg.text_content('#g-tx-range'))
    pg.select_option('#g-tx-pp', '50'); pg.wait_for_timeout(200)
    check('rows per page', pg.locator('#g-tx-body tr').count() == 50)
    pg.reload(); pg.wait_for_timeout(500)
    check('sort, page size persist on reload', pg.get_attribute('#g-tx th[data-key="gbp"]', 'aria-sort') == 'descending' and pg.locator('#g-tx-body tr').count() == 50)
    row = pg.locator('#g-tx-body tr').first; row.focus(); pg.keyboard.press('Enter'); pg.wait_for_timeout(400)
    check('Enter on a focused row opens the detail drawer', pg.evaluate("document.getElementById('drawer').classList.contains('open')") and pg.evaluate("document.activeElement.closest('#drawer') !== null"), pg.text_content('#drawer-t'))
    check('drawer id persisted in URL', 'p.open=TX' in pg.url)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    check('Escape closes the drawer and returns focus to the row', not pg.evaluate("document.getElementById('drawer').classList.contains('open')") and pg.evaluate("document.activeElement.matches('tr[data-grid-row]')"))
    # charts: tooltip, legend isolate, table disclosure, CSV copy button exists
    pg.goto(U('index.html')); pg.wait_for_timeout(600)
    m = pg.locator('#ch-exposure svg rect.dv-series').first; m.hover(position={'x': 4, 'y': 4}, force=True); pg.wait_for_timeout(250)
    tip = pg.evaluate("(()=>{const t=document.getElementById('dvTip'); return t? [getComputedStyle(t).opacity, getComputedStyle(t).visibility, t.textContent.trim()] : null})()")
    check('chart tooltip shows on hover', bool(tip) and tip[2] != '' and tip[1] != 'hidden', tip)
    pg.click('#ch-exposure .dv-leg-item[data-series="1"]'); pg.wait_for_timeout(300)
    iso = pg.evaluate("[...document.querySelectorAll('#ch-exposure [data-series-group]')].filter(e=>e.classList.contains('is-faded')||e.classList.contains('is-ghost')).length")
    check('legend isolate dims the other series', iso > 0 and pg.get_attribute('#ch-exposure .dv-leg-item[data-series="1"]', 'aria-pressed') == 'true', iso)
    pg.click('#ch-exposure .dv-leg-reset'); pg.wait_for_timeout(200)
    pg.click('#ch-liquidity summary.dv-tbl-toggle'); pg.wait_for_timeout(200)
    check('chart "View as table" opens its data table', pg.evaluate("document.querySelector('#ch-liquidity details.dv-tbl').open") and pg.locator('#ch-liquidity table.dv-table tbody tr').count() == 30)
    pg.click('#ch-exposure [data-exp-view="ccy"]'); pg.wait_for_timeout(300)
    check('exposure view switch re-draws by currency', pg.locator('#ch-exposure table.dv-table tbody tr').count() == 8)
    pg.click('#ch-exposure [data-exp-view="region"]'); pg.wait_for_timeout(300)
    # drill-through: click a column
    pg.locator('#ch-exposure svg rect.dv-series').first.click(position={'x': 4, 'y': 4}, force=True); pg.wait_for_timeout(900)
    reg = pg.evaluate("new URLSearchParams(location.search).get('region')")
    regs = set(pg.locator('#g-pos-body td:nth-child(2)').all_text_contents())
    check('exposure column drills through to positions and limits', 'risk.html' in pg.url and reg is not None and len(regs) == 1 and pg.locator('#reg-limits .lim').count() >= 1, (pg.url.split('/')[-1], regs))
    pg.goto(U('index.html')); pg.wait_for_timeout(400); pg.click('[data-ftb-clear]') if pg.locator('#ftb-chips .tag').count() else None
    pg.click('#drill a >> nth=2'); pg.wait_for_timeout(800)
    check('drill link opens risk scoped to that region at the positions grid', '#positions' in pg.url and 'region=' in pg.url, pg.url.split('/')[-1])
    check('no console errors in part 1', not errs, errs[:5])
    b.close()
json.dump(R, open(os.path.join(OUT, '_proof', 'drive', 'drive1.json'), 'w'), indent=1, default=str)
print('SUMMARY', sum(1 for r in R if r[0] == 'PASS'), 'pass', sum(1 for r in R if r[0] == 'FAIL'), 'fail')
