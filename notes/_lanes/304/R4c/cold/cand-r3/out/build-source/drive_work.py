# decisions: overview summary -> payment record -> approve (validated) -> audit; reject; persistence; drill-through
first = pg.locator('[data-summary="ov-approvals"] .l-stack a.tpl-link').first
pid = first.inner_text().split(' · ')[0]; first.click(); pg.wait_for_timeout(900)
check('pending-approval card links to the payment record (drawer open, URL carries the id)', ev(pg, "() => document.getElementById('drawer').classList.contains('open')") and pid in pg.url, [pid, pg.url])
check('focus moved into the drawer', ev(pg, "() => !!document.activeElement.closest('#drawer')"))
big = ev(pg, "id => window.CEO.DATA.payments.find(p => p.id === id).gbp >= 5e6", pid)
pg.click('#drawer-foot [data-drawer-act="0"]'); pg.wait_for_timeout(700)
check('Approve opens the confirmation dialog', ev(pg, "() => document.getElementById('overlay').classList.contains('open')"), txt(pg, '#dtitle'))
if big:
    pg.click('#confirm'); pg.wait_for_timeout(300)
    check('a £5m+ approval without a note is refused with an inline error', ev(pg, "() => !!document.querySelector('#modal-form .is-error [data-err]')"), txt(pg, '#modal-form'))
    pg.fill('#modal-form textarea', 'Approved for supplier settlement under Q3 plan.')
pg.click('#confirm'); pg.wait_for_timeout(900)
st = ev(pg, "id => window.CEO.DATA.payments.find(p => p.id === id).status", pid)
check('approval releases the payment and writes an audit entry', st == 'Released' and 'You (CEO)' in txt(pg, '#drawer-body'), st)
check('a confirmation toast is announced (role=status)', ev(pg, "() => [...document.querySelectorAll('#toastRegion .toast[role=status]')].some(t => /approved/.test(t.textContent))"))
pg.keyboard.press('Escape'); pg.wait_for_timeout(500)
check('Escape closes the drawer and the URL drops the record', not ev(pg, "() => document.getElementById('drawer').classList.contains('open')") and pid not in pg.url, pg.url)
# reject path on another pending payment
pg.goto(URL + '#/payments?status=Pending%20approval'); pg.wait_for_timeout(1000)
pending_rows = ev(pg, "() => [...document.querySelectorAll('#dg-pay tbody tr')].map(r => r.cells[7].innerText)")
check('status deep link filters the payments grid to pending approval', pending_rows and all(r == 'Pending approval' for r in pending_rows), pending_rows[:3])
pg.locator('#dg-pay tbody a.tpl-link').first.click(); pg.wait_for_timeout(800)
rid = pg.url.split('/payments/')[1].split('?')[0]
pg.click('#drawer-foot [data-drawer-act="1"]'); pg.wait_for_timeout(500)
pg.fill('#modal-form textarea', 'short'); pg.click('#confirm'); pg.wait_for_timeout(300)
check('rejection with a reason under 10 characters is refused', ev(pg, "() => document.getElementById('overlay').classList.contains('open') && !!document.querySelector('#modal-form [data-err]')"))
pg.fill('#modal-form textarea', 'Duplicate of an earlier invoice; supplier to reissue.'); pg.click('#confirm'); pg.wait_for_timeout(800)
check('rejection records the status', ev(pg, "id => window.CEO.DATA.payments.find(p => p.id === id).status", rid) == 'Rejected', rid)
pg.keyboard.press('Escape'); pg.wait_for_timeout(400)
pg.reload(); pg.wait_for_timeout(1400)
check('approve and reject outcomes survive a reload', ev(pg, "a => a.map(id => window.CEO.DATA.payments.find(p => p.id === id).status)", [pid, rid]) == ['Released', 'Rejected'])
# grid: sort, page, page size
pg.goto(URL + '#/payments'); pg.wait_for_timeout(1000)
pg.click('#dg-pay th[data-key="gbp"] button.sort'); pg.wait_for_timeout(300)
a1 = ev(pg, "() => [...document.querySelectorAll('#dg-pay tbody tr')].map(r => parseFloat(r.cells[6].innerText.replace(/[£m,]/g,'').replace('−','-')))")
check('sorting by GBP equivalent orders ascending and sets aria-sort', a1 == sorted(a1) and ev(pg, "() => document.querySelector('#dg-pay th[data-key=gbp]').getAttribute('aria-sort')") == 'ascending', a1[:4])
pg.click('#dg-pay th[data-key="gbp"] button.sort'); pg.wait_for_timeout(300)
a2 = ev(pg, "() => [...document.querySelectorAll('#dg-pay tbody tr')].map(r => parseFloat(r.cells[6].innerText.replace(/[£m,]/g,'').replace('−','-')))")
check('second click sorts descending', a2 == sorted(a2, reverse=True), a2[:4])
pg.click('#dg-pay [data-go="next"]'); pg.wait_for_timeout(300)
check('next page moves the range', txt(pg, '#pay-range').startswith('11–20'), txt(pg, '#pay-range'))
pg.select_option('#pay-pp', '25'); pg.wait_for_timeout(300)
check('rows per page 25 shows 25 rows', ev(pg, "() => document.querySelectorAll('#dg-pay tbody tr').length") == 25)
pg.reload(); pg.wait_for_timeout(1300)
check('sort and page size persist across reload', ev(pg, "() => document.querySelector('#dg-pay th[data-key=gbp]').getAttribute('aria-sort')") == 'descending' and ev(pg, "() => document.querySelectorAll('#dg-pay tbody tr').length") == 25)
# drill-through from the overview exposure chart
pg.goto(URL + '#/overview'); pg.wait_for_timeout(1200)
bar = pg.locator('[data-chart="ov-exposure"] rect.dv-series').first
lab = bar.get_attribute('data-tip') or bar.get_attribute('aria-label'); bar.click(); pg.wait_for_timeout(1100)
reg = ev(pg, "() => window.CEO.STATE.region")
check('clicking a region bar drills to Risk and limits, filtered to that region, on the positions tab', '#/risk' in pg.url and reg != 'all' and reg in (lab or '') and
      ev(pg, "() => document.querySelector('[data-tabs=\"rk-tabs\"] [aria-selected=true]').getAttribute('data-tab')") == 'positions', [lab, reg, pg.url])
regs = ev(pg, "() => [...new Set([...document.querySelectorAll('#dg-pos tbody tr')].map(r => r.cells[2].innerText))]")
check('the drilled positions all belong to that region', regs == [reg], regs)
