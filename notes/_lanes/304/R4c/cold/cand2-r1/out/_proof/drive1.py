import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from drive_common import *
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=os.environ["RENDER_SHELL"])
    ctx = b.new_context(viewport={"width": 1440, "height": 900})
    pg = ctx.new_page(); errs = []; attach(pg, errs)
    pg.goto(URL("index")); pg.wait_for_timeout(700)
    k0 = pg.get_attribute('.kpi-tile[data-kpi="cash"]', "aria-label")
    exp0 = tbl_rows(pg, "ov-exp")
    check("overview loads with 4 KPI tiles, 4 charts", pg.locator(".kpi-tile").count() == 4 and pg.locator("figure.dv").count() == 4)
    check("exposure chart has 4 regions x 5 currencies drawn", len(exp0) == 4 and pg.locator("#ov-exp rect.dv-series").count() >= 16, len(exp0))
    choose(pg, "f-entity", "E3")
    k1 = pg.get_attribute('.kpi-tile[data-kpi="cash"]', "aria-label")
    check("entity filter re-drives KPI", k0 != k1, "%s -> %s" % (k0, k1))
    check("entity filter re-drives exposure chart", tbl_rows(pg, "ov-exp") != exp0)
    check("URL carries the filter", "entity=E3" in pg.url, pg.url.split("/")[-1])
    check("entity dropdown shows the choice", "Americas Inc" in pg.inner_text("#f-entity .ddval"))
    seg(pg, "f-range", "7")
    check("range 7 days re-drives the line chart (7 rows)", len(tbl_rows(pg, "ov-liq")) == 7, len(tbl_rows(pg, "ov-liq")))
    k7 = pg.get_attribute('.kpi-tile[data-kpi="cash"]', "aria-label")
    check("range re-drives KPI delta period", "vs 19 Sep" in k7, k7)
    pg.reload(); pg.wait_for_timeout(700)
    check("reload keeps entity + range", "Americas Inc" in pg.inner_text("#f-entity .ddval") and pg.get_attribute('#f-range button[data-value="7"]', "aria-pressed") == "true" and len(tbl_rows(pg, "ov-liq")) == 7)
    nav = pg.get_attribute('a.sn-link[data-nav="payments"]', "href")
    check("nav links carry the shared filters", "entity=E3" in nav and "range=7" in nav, nav)
    # theme
    seg(pg, "f-theme", "dark")
    check("theme switch sets dark", pg.get_attribute("html", "data-theme") == "dark")
    pg.reload(); pg.wait_for_timeout(600)
    check("dark mode persists across reload", pg.get_attribute("html", "data-theme") == "dark")
    vis = pg.evaluate("() => [...document.querySelectorAll('.sh-mark')].map(i => i.dataset.mode + ':' + getComputedStyle(i).display)")
    check("dark masthead mark shown in dark mode", "dark:block" in vis and "light:none" in vis, vis)
    grd = pg.evaluate("() => [getComputedStyle(document.querySelector('.ceo-ground')).backgroundColor, getComputedStyle(document.querySelector('.stat-card.c-bento__tile')).backgroundColor, getComputedStyle(document.querySelector('.sh-main')).backgroundColor]")
    check("dark: section ground vs tile vs page (recorded)", True, grd)
    seg(pg, "f-theme", "light")
    grl = pg.evaluate("() => [getComputedStyle(document.querySelector('.ceo-ground')).backgroundColor, getComputedStyle(document.querySelector('.stat-card.c-bento__tile')).backgroundColor, getComputedStyle(document.querySelector('.sh-main')).backgroundColor, getComputedStyle(document.querySelector('.cn-page-header-lockup')).backgroundColor]")
    check("light: bento section lightest grey, tiles white, title area on page ground", grl[0] == "rgb(240, 240, 240)" and grl[1] == "rgb(255, 255, 255)", grl)
    # nav collapse
    pg.click('[data-navtoggle="shell"]'); pg.wait_for_timeout(300)
    check("nav collapses to rail", pg.get_attribute("#shell", "data-nav") == "rail")
    pg.reload(); pg.wait_for_timeout(600)
    check("rail persists across reload", pg.get_attribute("#shell", "data-nav") == "rail")
    pg.click('[data-navtoggle="shell"]'); pg.wait_for_timeout(300)
    check("nav expands again", pg.get_attribute("#shell", "data-nav") == "expanded")
    # reset filters to all for drill
    choose(pg, "f-entity", "all"); seg(pg, "f-range", "30")
    # drill: click an exposure column
    first = pg.locator("#ov-exp rect.dv-series").first
    lab = first.get_attribute("aria-label")
    first.click(position={"x": 20, "y": 5}, force=True); pg.wait_for_timeout(900)
    k2 = pg.url
    check("exposure column drills through to risk positions", "risk.html" in pg.url and "region=" in pg.url, (lab, pg.url.split("/")[-1]))
    reg = pg.inner_text("#f-region .ddval")
    check("risk page opens with the drilled region applied", reg in lab, reg)
    n = pg.locator("#tbody tr[data-id]").count()
    check("positions grid shows rows for that region", n > 0, n)
    # decision card -> record
    pg.goto(URL("index")); pg.wait_for_timeout(700)
    choose(pg, "f-region", "all")
    row = pg.locator("#ov-approvals a.row").first
    href = row.get_attribute("href"); row.click(); pg.wait_for_timeout(1200)
    check("pending-approval card links to the record (drawer open)", pg.locator("#sheet.open").count() == 1 and "Payment PAY-" in pg.inner_text("#dtitle"), href)
    foc = pg.evaluate("() => !!document.activeElement.closest('#sheet')")
    check("focus moves into the drawer", foc)
    pg.keyboard.press("Escape"); pg.wait_for_timeout(300)
    check("Escape closes the drawer", pg.locator("#sheet.open").count() == 0)
    pg.goto(URL("index")); pg.wait_for_timeout(700)
    row = pg.locator("#ov-exceptions a.row").first; row.click(); pg.wait_for_timeout(1200)
    check("risk-exception card links to an actionable record", pg.locator("#sheet.open").count() == 1 and pg.locator("#exc-note").count() == 1, pg.inner_text("#dtitle"))
    check("no console errors on overview journeys", not errs, errs[:5])
    b.close()
save("drive1")
