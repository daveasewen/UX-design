import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from drive_common import *
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=os.environ["RENDER_SHELL"])
    ctx = b.new_context(viewport={"width": 1440, "height": 900}, accept_downloads=True)
    pg = ctx.new_page(); errs = []; attach(pg, errs)
    # ---- risk: acknowledge with audit note
    pg.goto(URL("risk")); pg.wait_for_timeout(700)
    n0 = pg.locator("#rk-exc li").count()
    choose(pg, "rk-sev", "High")
    hi = pg.inner_text("#rk-exc-count")
    check("severity filter narrows the exception list", hi.startswith("3 "), hi)
    choose(pg, "rk-sev", "all")
    pg.fill("#rk-exc-q", "Lumen"); pg.wait_for_timeout(200)
    check("exception search", pg.inner_text("#rk-exc-count").startswith("1 "), pg.inner_text("#rk-exc-count"))
    pg.click("#rk-exc button.row"); pg.wait_for_timeout(500)
    pg.click("#act"); pg.wait_for_timeout(200)
    check("acknowledge without a note is refused", pg.get_attribute("#exc-note", "aria-invalid") == "true")
    pg.fill("#exc-note", "Reduce Lumen deposits by EUR 40m today; treasury to report back Tuesday.")
    pg.click("#act"); pg.wait_for_timeout(200)
    check("acknowledge without the confirmation box is refused", pg.locator("#exc-msg .alert").count() == 1)
    # keyboard: focus trap inside drawer
    pg.focus("#close")
    for i in range(14): pg.keyboard.press("Tab")
    check("Tab stays trapped in the drawer", pg.evaluate("() => !!document.activeElement.closest('#sheet')"))
    pg.click('label[for="exc-confirm"]'); pg.click("#act"); pg.wait_for_timeout(400)
    st = pg.inner_text("#rk-exc li:first-child .status")
    check("acknowledged exception changes status", st == "Acknowledged", st)
    pg.click("#rk-exc button.row"); pg.wait_for_timeout(500)
    tl = pg.locator("#dbody .tl-list li").count()
    check("audit trail records the acknowledgement with the note", tl == 2 and "Reduce Lumen" in pg.inner_text("#dbody .tl-list"), tl)
    pg.keyboard.press("Escape")
    pg.reload(); pg.wait_for_timeout(700)
    check("acknowledgement persists across reload", pg.inner_text("#rk-exc li:first-child .status") == "Acknowledged")
    lm = pg.locator("#rk-limits .lim-row").count()
    check("limit utilisation meters render", lm == 6, lm)
    pv = pg.eval_on_selector_all("#rk-limits .pb-track", "els => els.map(e => e.getAttribute('aria-valuetext'))")
    check("meters carry a text reading (not colour alone)", all("per cent" in x for x in pv), pv[:2])
    # ---- overview drill via the key letter (elementsFromPoint path)
    pg.goto(URL("index")); pg.wait_for_timeout(700)
    pg.locator("#ov-exp text.dv-barkey").first.click(); pg.wait_for_timeout(800)
    check("clicking the key letter on a column also drills", "risk.html" in pg.url and "region=" in pg.url, pg.url.split("/")[-1])
    # ---- messages: service request validation + submit; message reply
    pg.goto(URL("messages")); pg.wait_for_timeout(700)
    c0 = pg.inner_text("#sr-list-count")
    pg.click('[data-action="sr-submit"]'); pg.wait_for_timeout(300)
    errtxt = pg.inner_text("#sr-errors")
    check("empty service request is refused with named problems", "4 problems" in errtxt, errtxt[:120])
    check("invalid fields are marked", pg.get_attribute("#sr-subj", "aria-invalid") == "true" and pg.get_attribute("#sr-desc", "aria-invalid") == "true" and pg.get_attribute("#sr-cat-t", "aria-invalid") == "true")
    choose(pg, "sr-cat", "Payment investigation"); choose(pg, "sr-ent", "E2")
    pg.fill("#sr-subj", "Trace EUR supplier payment")
    pg.fill("#sr-desc", "SEPA payment SUP-44120 to Norland Steel AG not received by beneficiary after 3 days.")
    check("character counter follows typing", pg.inner_text("#sr-desc-count").startswith("8"), pg.inner_text("#sr-desc-count"))
    seg(pg, "sr-pri", "High")
    pg.click('[data-action="sr-submit"]'); pg.wait_for_timeout(400)
    c1 = pg.inner_text("#sr-list-count")
    check("valid request is submitted and listed", int(c1.split()[0]) == int(c0.split()[0]) + 1 and "submitted" in pg.inner_text("#toastRegion"), (c0, c1))
    pg.fill("#ms-list-q", "Know-your-customer"); pg.wait_for_timeout(200)
    pg.click("#ms-list button.row"); pg.wait_for_timeout(500)
    pg.click("#act"); pg.wait_for_timeout(200)
    check("empty reply refused", pg.get_attribute("#msg-reply", "aria-invalid") == "true")
    pg.fill("#msg-reply", "Documents will be uploaded by our company secretary on Monday."); pg.click("#act"); pg.wait_for_timeout(400)
    check("reply sent and message marked replied", "Replied" in pg.inner_text("#ms-list li:first-child .status"), pg.inner_text("#ms-list li:first-child .status"))
    pg.fill("#ms-list-q", ""); seg(pg, "ms-unread", "unread"); pg.wait_for_timeout(200)
    check("unread filter", "messages" in pg.inner_text("#ms-list-count") or "message" in pg.inner_text("#ms-list-count"), pg.inner_text("#ms-list-count"))
    seg(pg, "ms-unread", "all")
    pg.click('#ms-list-pg a[data-go="2"]'); pg.wait_for_timeout(200)
    check("list pagination", pg.get_attribute('#ms-list-pg a[data-go="2"]', "aria-current") == "page")
    # ---- reports: filter + CSV
    pg.goto(URL("reports")); pg.wait_for_timeout(700)
    choose(pg, "rp-fam", "Risk")
    check("report family filter", pg.inner_text("#rp-list-count").startswith("3 "), pg.inner_text("#rp-list-count"))
    pg.click("#rp-list button.row"); pg.wait_for_timeout(500)
    with pg.expect_download() as dl:
        pg.click("#act")
    d = dl.value; path = W + "/proof/export-" + d.suggested_filename; d.save_as(path)
    check("report CSV downloads", len(open(path).read().splitlines()) > 1, d.suggested_filename)
    # ---- accounts: range filter + row detail + export
    pg.goto(URL("accounts")); pg.wait_for_timeout(700)
    t30 = pg.inner_text("#dgCount"); seg(pg, "f-range", "7"); t7 = pg.inner_text("#dgCount")
    check("range filter re-drives the transactions grid", int(t7.split()[0]) < int(t30.split()[0]), (t30, t7))
    check("range filter re-drives the balances chart", len(tbl_rows(pg, "ac-bal")) == 7)
    pg.click("#tbody tr[data-id] td:nth-child(3)"); pg.wait_for_timeout(500)
    check("transaction detail shows FX rate used", "illustrative" in pg.inner_text("#dbody"), pg.inner_text("#dtitle"))
    pg.keyboard.press("Escape"); seg(pg, "f-range", "30")
    # ---- trade: amendment request creates a service request
    pg.goto(URL("trade")); pg.wait_for_timeout(700)
    ids = pg.eval_on_selector_all("#tbody tr[data-id]", "els => els.map(e => [e.dataset.id, e.children[4].textContent])")
    live = [i for i, t in ids if "Expired" not in t][0]
    pg.click('#tbody tr[data-id="%s"] td:nth-child(3)' % live); pg.wait_for_timeout(500)
    pg.fill("#tr-note", "Extend expiry by 60 days to match revised shipment schedule."); pg.click("#act"); pg.wait_for_timeout(400)
    check("trade amendment raises a service request", "raised with HSBC Trade Services" in pg.inner_text("#toastRegion"))
    # ---- fx + liquidity: filters re-drive charts
    pg.goto(URL("fx")); pg.wait_for_timeout(700)
    r0 = tbl_rows(pg, "fx-nat"); choose(pg, "f-region", "APAC"); r1 = tbl_rows(pg, "fx-nat")
    check("region filter re-drives FX exposure chart", r0 != r1)
    check("candlestick draws one candle per day", pg.locator("#fx-ohlc .dv-series, #fx-ohlc [data-series-group]").count() > 0 and len(tbl_rows(pg, "fx-ohlc")) == 30)
    pg.goto(URL("liquidity")); pg.wait_for_timeout(700)
    check("liquidity page inherits region filter via storage", "Asia Pacific" in pg.inner_text("#f-region .ddval"))
    check("bullet chart shows only that region's facilities", len(tbl_rows(pg, "liq-fac")) == 2, tbl_rows(pg, "liq-fac"))
    choose(pg, "f-region", "all")
    # ---- settings: prefs persist, reset
    pg.goto(URL("settings")); pg.wait_for_timeout(700)
    pg.click('label[for="n-messages"]'); pg.wait_for_timeout(200)
    seg(pg, "s-range", "14"); choose(pg, "s-entity", "E5")
    pg.reload(); pg.wait_for_timeout(600)
    check("notification preference persists", pg.is_checked("#n-messages"))
    check("default range + entity persist", pg.get_attribute('#s-range button[data-value="14"]', "aria-pressed") == "true" and "Asia Pacific" in pg.inner_text("#s-entity .ddval"))
    pg.click('[data-action="reset-data"]'); pg.wait_for_timeout(400)
    check("reset asks for confirmation in a modal", pg.locator("#mOverlay.open").count() == 1)
    pg.click("#mConfirm"); pg.wait_for_timeout(900)
    check("reset clears workflow state", pg.evaluate("() => localStorage.getItem('ceo.wf')") is None)
    check("no console errors across risk/messages/reports/accounts/trade/fx/liquidity/settings", not errs, errs[:5])
    b.close()
save("drive3")
