from drive_common import *
SHEET_GEO = """(()=>{const s=document.getElementById('sheet').getBoundingClientRect(); const bad=[...document.querySelectorAll('#sheet *')].filter(e=>{const r=e.getBoundingClientRect(); return r.width && (r.right>s.right+1||r.left<s.left-1)}).map(e=>(e.className.baseVal!==undefined?e.className.baseVal:e.className)+'').slice(0,4); return {w:Math.round(s.width), bad}})()"""
def isopen(pg): return pg.evaluate("document.getElementById('sheet').classList.contains('open')")
with sync_playwright() as p:
    b, ctx, errs = start(p); pg = ctx.new_page()
    # RISK
    pg.goto(URL('risk')); pg.wait_for_timeout(900)
    open0 = pg.text_content('#k-exc .amt')
    pg.click('[data-action="next-exception"]'); pg.wait_for_timeout(500)
    xid = pg.inner_text('#dtitle').split(' ')[0]
    pg.click('#sheet [data-dact="ack"]'); pg.wait_for_timeout(200)
    ok('acknowledge refuses a short note and an unticked review box', pg.evaluate("document.getElementById('ackNote-f').classList.contains('is-error') && !document.getElementById('ackChk-e').hidden"))
    g = pg.evaluate(SHEET_GEO); ok('drawer content stays inside the sheet', not g['bad'], g)
    pg.fill('#ackNote', 'Reviewed with Group Treasury; hedge top-up booked for Monday.'); pg.click('label[for="ackChk"]'); pg.click('#sheet [data-dact="ack"]'); pg.wait_for_timeout(500)
    ok('acknowledgement lands with an audit entry', not isopen(pg) and 'Acknowledged' in pg.inner_text('#toastRegion'), pg.inner_text('#toastRegion'))
    ok('open-exception KPI re-driven', pg.text_content('#k-exc .amt') != open0, open0 + ' -> ' + pg.text_content('#k-exc .amt'))
    pg.reload(); pg.wait_for_timeout(900)
    pg.fill('#ftbQ', xid); pg.wait_for_timeout(400)
    pg.locator('#gExc-body a[data-open]').first.scroll_into_view_if_needed(); pg.locator('#gExc-body a[data-open]').first.evaluate('e => e.click()'); pg.wait_for_timeout(500)
    ok('audit trail survives reload', 'Reviewed with Group Treasury' in pg.inner_text('#dbody') and 'Acknowledged' in pg.inner_text('#dbody'))
    pg.keyboard.press('Escape'); pg.fill('#ftbQ', ''); pg.wait_for_timeout(300)
    # LIQUIDITY drawdown
    pg.goto(URL('liquidity')); pg.wait_for_timeout(900)
    pg.click('[data-action="drawdown"]'); pg.wait_for_timeout(500)
    pg.fill('#ddAmt', '999999999999'); pg.fill('#ddWhy', 'short'); pg.click('#sheet [data-dact="submit"]'); pg.wait_for_timeout(200)
    ok('drawdown above headroom is refused', 'more than' in pg.inner_text('#ddAmt-e') and pg.evaluate("document.getElementById('ddWhy-f').classList.contains('is-error')"), pg.inner_text('#ddAmt-e'))
    pg.click('#ddFacT'); pg.wait_for_timeout(150); pg.locator('#ddFacM [role=option]').nth(1).click(); pg.wait_for_timeout(500)
    ok('facility picker re-targets the drawdown', isopen(pg) and pg.inner_text('#dtitle') != '', pg.inner_text('#dtitle'))
    pg.fill('#ddAmt', '25000000'); pg.fill('#ddWhy', 'Bridge the Q4 capex programme ahead of receipts.'); pg.click('#sheet [data-dact="submit"]'); pg.wait_for_timeout(500)
    ok('valid drawdown request is recorded', not isopen(pg) and 'Drawdown request' in pg.inner_text('#toastRegion') and pg.evaluate("JSON.parse(localStorage.getItem('apollo-ceo-proto-v1')).drawdowns.length") == 1)
    # FX quote and book
    pg.goto(URL('fx')); pg.wait_for_timeout(900)
    n0 = int(pg.inner_text('#gDeals-count').split(' ')[0])
    pg.click('[data-action="quote"]'); pg.wait_for_timeout(500)
    pg.click('#qPairT'); pg.wait_for_timeout(150); pg.click('#qPairM [data-value="GBP/EUR"]'); pg.wait_for_timeout(150)
    pg.fill('#qAmt', '500'); pg.click('#sheet [data-dact="price"]'); pg.wait_for_timeout(200)
    ok('quote below the minimum is refused', not pg.locator('#qAmt-e').is_hidden(), pg.inner_text('#qAmt-e'))
    pg.fill('#qAmt', '2,500,000'); pg.click('#sheet [data-dact="price"]'); pg.wait_for_timeout(300)
    ok('indicative rate is shown for the chosen pair', 'EUR per GBP' in pg.inner_text('#qOut'), pg.inner_text('#qOut')[:80])
    pg.click('#sheet [data-dact="book"]'); pg.wait_for_timeout(300); pg.click('#mconfirm'); pg.wait_for_timeout(500)
    ok('booked deal appears in the deals grid', int(pg.inner_text('#gDeals-count').split(' ')[0]) == n0 + 1, pg.inner_text('#gDeals-count'))
    # TRADE amendment
    pg.goto(URL('trade')); pg.wait_for_timeout(900)
    pg.click('[data-action="amend"]'); pg.wait_for_timeout(500)
    pg.click('#sheet [data-dact="send"]'); pg.wait_for_timeout(200)
    ok('amendment without details is refused', pg.evaluate("document.getElementById('tfWhy-f').classList.contains('is-error')"))
    pg.click('#tfKindT'); pg.wait_for_timeout(150); pg.click('#tfKindM [data-value="Increase amount"]'); pg.wait_for_timeout(150)
    pg.fill('#tfWhy', 'Increase by USD 2m to cover the second shipment.'); pg.click('#sheet [data-dact="send"]'); pg.wait_for_timeout(500)
    ok('amendment raises a service request', 'sent to the trade finance desk' in pg.inner_text('#toastRegion'), pg.inner_text('#toastRegion'))
    # MESSAGES
    pg.goto(URL('messages')); pg.wait_for_timeout(900)
    s0 = int(pg.inner_text('#gSr-count').split(' ')[0])
    ok('trade amendment arrived in service requests', 'Increase amount' in pg.inner_text('#gSr-body'))
    pg.click('[data-action="new-sr"]'); pg.wait_for_timeout(500)
    pg.fill('#srSum', 'Hi'); pg.click('#sheet [data-dact="submit"]'); pg.wait_for_timeout(200)
    ok('new request validates summary and details', pg.evaluate("document.getElementById('srSum-f').classList.contains('is-error') && document.getElementById('srDet-f').classList.contains('is-error')"))
    pg.fill('#srSum', 'Add two signatories to Europe GmbH'); pg.fill('#srDet', 'Please add the new CFO and deputy treasurer with dual-control rights on EUR accounts.')
    pg.click('#srPriT'); pg.wait_for_timeout(150); pg.click('#srPriM [data-value="High"]'); pg.wait_for_timeout(150)
    pg.click('#sheet [data-dact="submit"]'); pg.wait_for_timeout(500)
    ok('new service request is listed', int(pg.inner_text('#gSr-count').split(' ')[0]) == s0 + 1 and 'Add two signatories' in pg.inner_text('#gSr-body'), pg.inner_text('#gSr-count'))
    pg.locator('#gMsg-body a[data-open]').first.scroll_into_view_if_needed(); pg.locator('#gMsg-body a[data-open]').first.evaluate('e => e.click()'); pg.wait_for_timeout(500)
    pg.fill('#reply', 'Thank you — please send the term sheets to the treasurer too.'); pg.click('#sheet [data-dact="send"]'); pg.wait_for_timeout(500)
    ok('reply is sent and the message shows Replied', 'Replied' in pg.inner_text('#gMsg-body'), pg.inner_text('#toastRegion')[-60:])
    # REPORTS
    pg.goto(URL('reports')); pg.wait_for_timeout(900)
    with pg.expect_download() as dl:
        pg.click('[data-action="run-board"]')
    ok('board pack runs and downloads a CSV', dl.value.suggested_filename.endswith('.csv'), dl.value.suggested_filename)
    pg.locator('#gRep-body a[data-open]').first.scroll_into_view_if_needed(); pg.locator('#gRep-body a[data-open]').first.evaluate('e => e.click()'); pg.wait_for_timeout(400)
    with pg.expect_download() as dl2:
        pg.click('#sheet [data-dact="rundl"]')
    ok('any report runs and downloads', dl2.value.suggested_filename.startswith('RPT-'), dl2.value.suggested_filename)
    # ACCOUNTS
    pg.goto(URL('accounts')); pg.wait_for_timeout(900)
    pg.locator('#gAcc-body a[data-open]').first.scroll_into_view_if_needed(); pg.locator('#gAcc-body a[data-open]').first.evaluate('e => e.click()'); pg.wait_for_timeout(400)
    with pg.expect_download() as dl3:
        pg.click('#sheet [data-dact="stmt"]')
    ok('account statement downloads', dl3.value.suggested_filename.endswith('statement.csv'), dl3.value.suggested_filename)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    pg.locator('#gTx-body a[data-open]').first.scroll_into_view_if_needed(); pg.locator('#gTx-body a[data-open]').first.evaluate('e => e.click()'); pg.wait_for_timeout(400)
    pg.click('#sheet [data-dact="investigate"]'); pg.wait_for_timeout(400)
    ok('transaction investigation raises a request', 'raised' in pg.inner_text('#toastRegion'))
    # SETTINGS
    pg.goto(URL('settings')); pg.wait_for_timeout(900)
    v0 = pg.evaluate("document.querySelector('#ch-alerts table.dv-table tbody tr:nth-child(4) td').textContent")
    pg.click('label[for="n-digest"]'); pg.wait_for_timeout(300)
    v1 = pg.evaluate("document.querySelector('#ch-alerts table.dv-table tbody tr:nth-child(4) td').textContent")
    ok('notification toggle re-drives the alerts chart', v0 != v1, v0 + ' -> ' + v1)
    pg.click('#themeSeg2 [data-theme-set="dark"]'); pg.wait_for_timeout(300)
    ok('settings theme control switches theme everywhere', pg.get_attribute('html', 'data-theme') == 'dark' and pg.get_attribute('#themeSeg [data-theme-set="dark"]', 'aria-pressed') == 'true')
    pg.click('[data-action="reset"]'); pg.wait_for_timeout(300)
    ok('reset asks first', pg.evaluate("document.getElementById('overlay').classList.contains('open')"))
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    ok('Escape cancels the reset and keeps the data', not pg.evaluate("document.getElementById('overlay').classList.contains('open')") and pg.evaluate("!!localStorage.getItem('apollo-ceo-proto-v1')"))
    ok('no console errors or page errors (scenario C)', not errs, errs[:3])
    b.close()
save('C')
