from drive_common import *
with sync_playwright() as p:
    b, ctx, errs = start(p); pg = ctx.new_page(); pg.goto(URL('payments')); pg.wait_for_timeout(900)
    mine0 = pg.text_content('#k-mine .delta')
    pg.click('[data-action="next-approval"]'); pg.wait_for_timeout(500)
    ok('approve-next opens the drawer', pg.evaluate("document.getElementById('sheet').classList.contains('open')"), pg.inner_text('#dtitle'))
    ok('focus moved into the drawer', pg.evaluate("document.getElementById('sheet').contains(document.activeElement)"))
    ok('background is inert while the drawer is open', pg.evaluate("document.querySelector('main.tpl-page').inert"))
    pid = pg.inner_text('#dtitle').replace('Payment ', '')
    pg.click('#sheet [data-dact="reject"]'); pg.wait_for_timeout(200)
    ok('reject without a reason is refused (error state)', pg.evaluate("document.getElementById('payNote-f').classList.contains('is-error') && document.getElementById('payNote').getAttribute('aria-invalid')==='true'"), pg.inner_text('#payNote-e'))
    pg.fill('#payNote', 'Duplicate of the supplier run released on Monday.'); pg.wait_for_timeout(100)
    ok('counter tracks the note', pg.inner_text('#payNote-c').startswith(str(len('Duplicate of the supplier run released on Monday.')) + '/'), pg.inner_text('#payNote-c'))
    pg.click('#sheet [data-dact="reject"]'); pg.wait_for_timeout(500)
    ok('reject closes the drawer and toasts', (not pg.evaluate("document.getElementById('sheet').classList.contains('open')")) and 'Rejected' in pg.inner_text('#toastRegion'), pg.inner_text('#toastRegion'))
    ok('decision persisted to the store', pg.evaluate("JSON.parse(localStorage.getItem('apollo-ceo-proto-v1')).decisions['%s'].status" % pid) == 'Rejected')
    ok('KPI re-driven by the decision', pg.text_content('#k-mine .delta') != mine0, mine0 + ' -> ' + pg.text_content('#k-mine .delta'))
    # material approval with modal
    pg.click('#payView [data-view="mine"]'); pg.wait_for_timeout(400)
    ok('needs-me view filters the grid and URL', 'status=mine' in pg.url and 'Needs me' in pg.inner_text('#ftbChips'), pg.inner_text('#gPay-count'))
    pg.click('#gPay th[data-key="gbp"] .sort'); pg.wait_for_timeout(200); pg.click('#gPay th[data-key="gbp"] .sort'); pg.wait_for_timeout(300)
    ok('sort cycles to descending', pg.get_attribute('#gPay th[data-key="gbp"]', 'aria-sort') == 'descending')
    pg.locator('#gPay-body a[data-open]').first.scroll_into_view_if_needed(); pg.locator('#gPay-body a[data-open]').first.evaluate('e => e.click()'); pg.wait_for_timeout(500)
    material = pg.locator('#sheet .cn-alert').count() > 0
    ok('largest pending payment is flagged material', material, pg.inner_text('#dtitle'))
    pg.click('#sheet [data-dact="approve"]'); pg.wait_for_timeout(200)
    ok('material approval without a note is refused', pg.evaluate("document.getElementById('payNote-f').classList.contains('is-error')"))
    pg.fill('#payNote', 'Board approved capex tranche two, minute 14.'); pg.click('#sheet [data-dact="approve"]'); pg.wait_for_timeout(400)
    ok('material approval asks for confirmation (modal)', pg.evaluate("document.getElementById('overlay').classList.contains('open')"), pg.inner_text('#mbody')[:90])
    ok('modal takes focus', pg.evaluate("document.getElementById('overlay').contains(document.activeElement)"))
    pg.click('#mconfirm'); pg.wait_for_timeout(500)
    ok('approval lands (toast + drawer closed)', 'Approved' in pg.inner_text('#toastRegion') and not pg.evaluate("document.getElementById('sheet').classList.contains('open')"))
    # escape + focus return
    pg.click('#payView [data-view="all"]'); pg.wait_for_timeout(300)
    link = pg.locator('#gPay-body a[data-open]').first; lid = link.get_attribute('data-open'); link.focus(); link.press('Enter'); pg.wait_for_timeout(500)
    ok('opening a record writes it to the URL', ('id=' + lid) in pg.url, pg.url)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(300)
    ok('Escape closes the drawer and returns focus', (not pg.evaluate("document.getElementById('sheet').classList.contains('open')")) and pg.evaluate("document.activeElement.getAttribute('data-open')") == lid)
    # paging, page size, sort by due
    r0 = pg.inner_text('#gPay-range'); pg.click('#gPay-pg [data-go="next"]'); pg.wait_for_timeout(300)
    ok('pager moves to page 2', pg.inner_text('#gPay-range') != r0, r0 + ' -> ' + pg.inner_text('#gPay-range'))
    pg.select_option('#gPay-pp', '25'); pg.wait_for_timeout(300)
    ok('rows per page = 25', pg.locator('#gPay-body tr').count() == min(25, int(pg.inner_text('#gPay-count').split(' ')[0])), pg.locator('#gPay-body tr').count())
    pg.fill('#ftbQ', 'Halden'); pg.wait_for_timeout(500)
    n = int(pg.inner_text('#gPay-count').split(' ')[0])
    ok('search narrows the grid and lands in the URL', 0 < n < 40 and 'q=Halden' in pg.url, pg.inner_text('#gPay-count'))
    with pg.expect_download() as dl:
        pg.click('#fExportT'); pg.wait_for_timeout(150); pg.click('#fExportM [data-value="csv"]')
    d = dl.value; path = d.path(); body = open(path).read()
    ok('export downloads a CSV of the filtered rows', d.suggested_filename.endswith('.csv') and body.count('\n') == n, d.suggested_filename + ' lines=' + str(body.count('\n') + 1))
    pg.reload(); pg.wait_for_timeout(900)
    ok('reload keeps search, page size and sort', pg.input_value('#ftbQ') == 'Halden' and pg.input_value('#gPay-pp') == '25', pg.url)
    pg.fill('#ftbQ', ''); pg.wait_for_timeout(400)
    st = pg.evaluate("[...document.querySelectorAll('#gPay-body tr')].filter(t=>t.dataset.id==='%s').map(t=>t.textContent)" % pid)
    pg.fill('#ftbQ', pid); pg.wait_for_timeout(400)
    ok('rejected payment shows Rejected after reload', 'Rejected' in pg.inner_text('#gPay-body'), pg.inner_text('#gPay-body')[:120])
    pg.fill('#ftbQ', ''); pg.wait_for_timeout(300)
    ok('no console errors or page errors (scenario B)', not errs, errs[:3])
    b.close()
save('B')
