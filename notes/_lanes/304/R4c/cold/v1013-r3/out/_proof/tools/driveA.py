from drive_common import *
with sync_playwright() as p:
    b, ctx, errs = start(p); pg = ctx.new_page(); pg.goto(URL('index')); pg.wait_for_timeout(800)
    cash0 = pg.text_content('#k-cash .amt'); ok('overview KPI cash rendered from DATA', cash0.strip() not in ('', '—'), cash0)
    ok('three decision rows render', pg.locator('#naList a').count() > 0 and pg.locator('#exList a').count() > 0, (pg.locator('#naList a').count(), pg.locator('#exList a').count()))
    pick(pg, 'fRegion', 'Europe')
    cash1 = pg.text_content('#k-cash .amt')
    ok('region filter re-drives the cash KPI', cash1 != cash0, cash0 + ' -> ' + cash1)
    ok('region filter re-drives the exposure chart', pg.locator('#ch-exposure table.dv-table tbody tr').count() == 1, pg.locator('#ch-exposure table.dv-table tbody tr').count())
    ok('region filter re-drives the trend chart', True if pg.evaluate("document.querySelector('#ch-trend table.dv-table tbody tr td').textContent") else False)
    ok('filter state in URL', 'region=Europe' in pg.url, pg.url)
    ok('applied-filter chip shown', 'Region: Europe' in pg.inner_text('#ftbChips'), pg.inner_text('#ftbChips'))
    ok('toolbar state is filtered', pg.get_attribute('#ftb', 'data-ftb-state') == 'filtered')
    pg.click('#themeSeg [data-theme-set="dark"]'); pg.wait_for_timeout(300)
    ok('theme switch sets data-theme=dark on <html>', pg.get_attribute('html', 'data-theme') == 'dark')
    ind = pg.evaluate("(() => { const s=document.querySelector('#themeSeg'), i=s.querySelector('.ind'), b=s.querySelector('[aria-pressed=true]'); return Math.abs(i.getBoundingClientRect().left-b.getBoundingClientRect().left) })()")
    ok('segmented indicator sits under the pressed segment', ind < 1.5, ind)
    pg.reload(); pg.wait_for_timeout(800)
    ok('reload keeps theme', pg.get_attribute('html', 'data-theme') == 'dark')
    ok('reload keeps region filter', pg.inner_text('#fRegionT .ddval') == 'Europe' and pg.text_content('#k-cash .amt') == cash1, pg.inner_text('#fRegionT .ddval'))
    pg.click('#ftbChips [data-chip="region"]'); pg.wait_for_timeout(400)
    ok('chip removal clears the filter and the URL', 'region=' not in pg.url and pg.text_content('#k-cash .amt') == cash0, pg.url)
    pick(pg, 'fDays', '7')
    ok('date range filter re-drives the trend chart (7 rows)', pg.locator('#ch-trend table.dv-table tbody tr').count() == 7, pg.locator('#ch-trend table.dv-table tbody tr').count())
    pick(pg, 'fEntity', 'E05')
    ok('entity filter sets its region and narrows decisions', pg.inner_text('#fRegionT .ddval') == 'Asia Pacific', pg.inner_text('#fRegionT .ddval'))
    pg.click('[data-ftb-clear]'); pg.wait_for_timeout(400)
    ok('clear all resets filters', pg.inner_text('#fEntityT .ddval') == 'All entities' and pg.locator('#ch-trend table.dv-table tbody tr').count() == 30)
    # legend isolate
    pg.click('#ch-exposure .dv-leg-item[data-series="2"]'); pg.wait_for_timeout(300)
    faded = pg.evaluate("document.querySelectorAll('#ch-exposure .is-faded, #ch-exposure .is-ghost').length")
    ok('legend isolate fades the other series', faded > 0, faded)
    pg.click('#ch-exposure .dv-leg-reset'); pg.wait_for_timeout(300)
    ok('legend reset restores', pg.evaluate("document.querySelectorAll('#ch-exposure .is-faded').length") == 0)
    # tooltip
    r = pg.locator('#ch-exposure rect.dv-series').first; r.hover(position={'x': 3, 'y': 2}); pg.wait_for_timeout(200)
    tip = pg.evaluate("(() => { const t=document.getElementById('dvTip'); return t && t.classList.contains('on') ? t.textContent : '' })()")
    ok('chart tooltip shows on hover', bool(tip), tip)
    pg.click('#ch-exposure summary.dv-tbl-toggle'); pg.wait_for_timeout(200)
    ok('view-as-table opens', pg.evaluate("document.querySelector('#ch-exposure details.dv-tbl').open"))
    # drill-through
    pg.click('#ch-exposure summary.dv-tbl-toggle'); pg.wait_for_timeout(200)
    ok('view-as-table closes again', not pg.evaluate("document.querySelector('#ch-exposure details.dv-tbl').open"))
    pg.locator('#ch-exposure rect[data-drill]').first.click(position={'x': 3, 'y': 2}); pg.wait_for_load_state(); pg.wait_for_timeout(800)
    ok('exposure bar drills to risk positions', 'risk.html' in pg.url and 'ccy=' in pg.url, pg.url)
    ok('drill arrives filtered (region + currency chips)', 'Currency:' in pg.inner_text('#ftbChips') and 'Region:' in pg.inner_text('#ftbChips'), pg.inner_text('#ftbChips'))
    ok('positions grid is scoped by the drill', 'positions' in pg.inner_text('#gPos-count'), pg.inner_text('#gPos-count'))
    pg.goto(URL('index')); pg.wait_for_timeout(800)
    pg.click('[data-ftb-clear]') if pg.locator('[data-ftb-clear]').is_visible() else None
    pg.locator('#naList a').first.click(); pg.wait_for_load_state(); pg.wait_for_timeout(900)
    ok('decision card opens the payment record', 'payments.html' in pg.url and pg.evaluate("document.getElementById('sheet').classList.contains('open')"), pg.inner_text('#dtitle'))
    pg.goto(URL('index')); pg.wait_for_timeout(700)
    pg.locator('#exList a').first.click(); pg.wait_for_load_state(); pg.wait_for_timeout(900)
    ok('exception card opens the exception record', 'risk.html' in pg.url and 'EXC-' in pg.inner_text('#dtitle'), pg.inner_text('#dtitle'))
    pg.goto(URL('index')); pg.wait_for_timeout(700)
    pg.click('#k-cash'); pg.wait_for_load_state(); pg.wait_for_timeout(500)
    ok('whole KPI card is clickable', 'accounts.html' in pg.url, pg.url)
    ok('no console errors or page errors (scenario A)', not errs, errs[:3])
    b.close()
save('A')
