    # that only checked for the canon class would pass with the old rules still shipping
    # underneath, which is the way a re-point silently becomes an addition.
    css = photo.split("<style>", 1)[1].split("</style>", 1)[0]
    _cssbody = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    # ⚠ Scoped to rules that TARGET a bento — the lightbox's own `display:grid` definition list
    # is not bento structure, and a blanket ban on the grid properties would have said so
    # falsely (caught on the first run of this bite).
    _bento_structure = [
        sel.strip() for sel, decls in re.findall(r"([^{}]+)\{([^{}]*)\}", _cssbody)
        if ("c-bento" in sel or "bx-" in sel)
        and re.search(r"grid-template-columns|grid-auto-rows|grid-auto-flow|gap\s*:|border-radius", decls)
    ]
    bite("6 · the pages CONSUME the canon bento (s217-D2), and declare no structure of their own",
         (("c-bento__grid" in photo and "c-bento__grid" in logos),
          ("bx-grid" in photo + logos + css),
          _bento_structure,
          bool(re.search(r"@container", _cssbody))),
         (True, False, [], False))
    pbody = photo.split("</style>", 1)[1]
    lbody = logos.split("</style>", 1)[1]
    # ⛔ THE DANGLING-VAR FENCE, and the SCOPE of it is the point. A page-local name declared in
    # this same stylesheet cannot dangle — it is defined two lines up. What CAN dangle is a
    # CANON property this page reads but does not own: rename it upstream, or land in a theme
    # that never defines it, and the page renders SILENT BLACK with no gate to catch it
    # ([[dangling-dataviz-var-renders-silent-black]]). So the bite is: every var() whose target
    # this stylesheet does NOT declare must carry a literal fallback.
    # ⚠ comments are STRIPPED first: the fence is about the rules that ship, and a `var(--x)`
    # quoted inside a `/* … */` note is prose. Measuring the raw string read the comment above
    # `.fx, header.app` and reported a dangle that does not exist.
    rules = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    declared = set(re.findall(r"(--[a-z0-9-]+)\s*:", rules))
    bare = sorted({m for m in re.findall(r"var\((--[a-z0-9-]+)\s*\)", rules)
                   if m not in declared})
    bite("7 · ⛔ no FOREIGN var() is read without a literal fallback (silent-black class)",
         bare, [])
    bite("8 · every photograph caption is the manifest's own text, never invented",
         all(esc(r["description"]) in photo or r["description"] == "UNKNOWN"
             for r in rows["photography"]), True)
    bite("9 · the full population is stated on the page, not just the derivative count",
         ("251 originals" in photo and "s217-D1" in photo), True)
    # ⚠ counted over the MARKUP, not the file: the shared stylesheet carries the two
