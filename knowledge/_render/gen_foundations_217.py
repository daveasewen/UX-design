def esc(s):
    return htmlmod.escape(str(s if s is not None else ""), quote=True)


def shell(title, h1, subtitle, body, extra_css="", extra_script="", extra_class=""):
    """THE ONE PAGE SHELL for every Foundations entry.

    ⚠ `extra_css` / `extra_script` / `extra_class` exist for ONE reason (#217, the bento matrix
    explorer): a Foundations entry that is an INSTRUMENT needs its own controller styles and its
    own behaviour, and the alternative was a second shell. A second shell is how the theme
    broadcast, the `#chrome=0` embed contract and the head order fork. The extra blocks are
    ADDITIVE and page-scoped; nothing here reaches canon."""
    return ((HEAD
             .replace("__TITLE__", esc(title))
             .replace("__SENTINEL__", SENTINEL)
             .replace("__UP__", UP)
             .replace("__CSS__", CSS)
             .replace("__EXTRA_CSS__",
                      ("\n<style>%s</style>" % extra_css) if extra_css.strip() else "")
             .replace("__H1__", esc(h1))
             # ⚠ the space is part of the SLOT, not the value: with it in the template every
             # existing page's <body> would gain a trailing space and rewrite on the next run —
             # a diff on two signed-off pages for an addition that does not touch them.
             .replace("__EXTRA_CLASS__", (" %s" % extra_class) if extra_class else "")
             .replace("__SUBTITLE__", subtitle))
            + body + TAIL.replace("__SCRIPT__", SCRIPT)
                         # ⚠ EMITTED ONLY WHEN THERE IS ONE. An empty `<script>` tag would be
                         # invisible to a reader and LOUD to a gate: the photography page's
                         # zero-JavaScript-lightbox bite counts script tags, and a shell that
                         # always emits two would have made that bite unfailable-in-reverse.
                         .replace("__EXTRA_SCRIPT__",
                                  ("\n<script>%s</script>" % extra_script)
                                  if extra_script.strip() else ""))


