def fill_label(v):
    v = v.strip()
    low = v.lower()
    if low in ("#ffffff", "white", "#fff"):
        return "white", "#FFFFFF"
    if low in ("#000000", "black", "#000"):
        return "black", "#000000"
    return v.upper() if v.startswith("#") else v, v


def read_logos():
    """-> (rows, residuals). Every field measured off the file; nothing typed."""
    rows, missing = [], []
    for lockup in LOGO_ORDER:
        for ground in ("light", "dark"):
            for ink in ("colour", "mono"):
                name = "%s-%s-%s.svg" % (lockup, ground, ink)
                path = os.path.join(LOGO_DIR, name)
                if not os.path.exists(path):
                    missing.append(name)
                    continue
                src = open(path, encoding="utf-8").read()
                vb = VIEWBOX_RE.search(src)
                vbox = vb.group(1).strip() if vb else None
                w = h = None
                if vbox:
                    parts = vbox.split()
                    if len(parts) == 4:
                        try:
                            w, h = float(parts[2]), float(parts[3])
                        except ValueError:
                            w = h = None
                # ⚠ `fill="none"` is a PAINT INSTRUCTION, not a colour, and it has no swatch
                # to draw. Counting it produced an empty chip reading `none ×1` on every tile.
                # It is excluded from the inventory and the inventory says "painted fills".
                counts = {}
                for f in FILL_RE.findall(src):
                    if f.strip().lower() in ("none", "transparent", "currentcolor"):
                        continue
                    lbl, swatch = fill_label(f)
                    key = (lbl, swatch)
                    counts[key] = counts.get(key, 0) + 1
                rows.append({
                    "file": name,
                    "lockup": lockup,
                    "lockup_label": LOGO_LOCKUP[lockup][0],
                    "ground": ground,
                    "ink": ink,
                    "viewbox": vbox or "UNKNOWN",
                    "w": w, "h": h,
                    "bytes": os.path.getsize(path),
                    "fills": [{"label": k[0], "swatch": k[1], "n": n}
                              for k, n in sorted(counts.items(), key=lambda kv: -kv[1])],
                    "span": span_for(w, h),
                })
    return rows, {"missing": missing}


def read_photos():
    """-> (rows, meta, residuals). Rows are the manifest's OWN rows that carry a derivative."""
    if not os.path.exists(PHOTO_MANIFEST):
        return [], {}, {"manifest": "MISSING"}
    d = json.load(open(PHOTO_MANIFEST, encoding="utf-8"))
    rows, missing = [], []
    for r in d.get("rows", []):
        deriv = r.get("derivative")
        if not deriv:
            continue
        if not os.path.exists(os.path.join(PHOTO_WEB, deriv)):
            missing.append(deriv)
            continue
        px = r.get("derivative_px") or ""
        w = h = None
        if "x" in px:
            try:
                w, h = (int(x) for x in px.split("x", 1))
            except ValueError:
                w = h = None
        rows.append({
            "file": deriv,
            "original": r.get("filename"),
            "w": w, "h": h,
            "orientation": r.get("orientation") or "UNKNOWN",
            # ⚠ null in the manifest means the field is ABSENT on the file. It is reported as
            # UNKNOWN here and never defaulted to a plausible sentence.
            "description": r.get("exif_description") or "UNKNOWN",
            "description_basis": r.get("exif_description_basis") or "UNKNOWN",
            "licence": r.get("licence_source") or "UNKNOWN",
            "licence_basis": r.get("licence_source_basis") or "UNKNOWN",
            "bytes": r.get("derivative_bytes") or 0,
            "src_px": "%s×%s" % (r.get("width"), r.get("height")),
            "span": span_for(w, h),
        })
    rows.sort(key=lambda r: r["file"])
    for i, r in enumerate(rows, 1):
        r["span"] = emphasise(r["span"], i)
    # THE SQUARING PASS — RATIFIED s217-D3, and this wall is EXEMPT from it. The policy is
    # ASKED, never re-decided here: `square_wall_for_role` reads role=gallery out of the store
    # and returns the wall untouched, reporting its raggedness as acceptable rather than as a
    # failure. An `if role == "gallery"` in this file would be a second source for a ruled fact.
    # ⚠ The wall is dialled to 4 columns (`.fx-wall-photo`), so its LADDER is 4/3/2/1 — a wall
    # never renders wider than its own dial.
    # ⚠ EXEMPT FROM SQUARING IS NOT EXEMPT FROM THE ASPECT MAPPING. `span_for`/`emphasise` above
    # still run, so portraits are still two rows tall — that mapping IS the "appropriate layout
    # for portrait and landscape images" the gallery role asks for. Different mechanisms.
    squared, srep = square_wall_for_role([r["span"] for r in rows], PHOTO_ROLE,
                                         ladder=PHOTO_LADDER)
    if srep["squared"] and not srep.get("exempt"):
        for r, s in zip(rows, squared):
            r["span"] = s
    return rows, d, {"missing_derivative_file": missing, "squaring": srep}


