def foreign_props(src):
    """The CANON properties THIS PAGE'S OWN stylesheet reads — derived from the page, so the probe
    cannot drift from what ships. ⚠ `--bento-*` and `--layout-bento-*` are excluded and the reason
    is a measured false red (#217): this sweep resolves names against `document.body`, which is
    the right question for a root-tier token and the WRONG one for a property canon declares on
    `.c-bento`. Those are probed on their own elements by MEASURE instead."""
    blocks = re.findall(r"<style>(.*?)</style>", src, flags=re.S)
    css = re.sub(r"/\*.*?\*/", "", "\n".join(blocks), flags=re.S)
    declared = set(re.findall(r"(--[a-z0-9-]+)\s*:", css))
    read = set(re.findall(r"var\((--[a-z0-9-]+)", css))
    return sorted(p for p in (read - declared)
                  if not p.startswith("--bento-") and not p.startswith("--layout-bento-"))


